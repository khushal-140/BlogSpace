def populate_demo_data():
    """Insert all demo users and posts into the database.

    Idempotent: does nothing when posts already exist, so it is safe to call
    on every startup. Returns True when seeding actually happened.
    """
    if Post.query.first() is not None:
        return False

    demo_hash = bcrypt.generate_password_hash(DEMO_PASSWORD).decode('utf-8')
    admin_hash = bcrypt.generate_password_hash(ADMIN_PASSWORD).decode('utf-8')

    for spec in USERS:
        user = User.query.filter_by(username=spec['username']).first()
        if user is None:
            user = User(username=spec['username'], email=spec['email'], image=spec['image'],
                        password=admin_hash if spec.get('is_admin') else demo_hash,
                        is_admin=spec.get('is_admin', False))
            db.session.add(user)
        user.profession = spec['profession']
        user.bio = spec['bio']
    db.session.commit()

    now = datetime.utcnow()
    for spec in POSTS:
        author = User.query.filter_by(username=spec['author']).first()
        db.session.add(Post(title=spec['title'], content=spec['content'], author=author,
                            category=spec['category'], is_featured=spec.get('featured', False),
                            date_posted=now - timedelta(days=spec['days_ago'])))
    db.session.commit()

    print(f'[BlogSpace] Seeded {len(USERS)} users and {len(POSTS)} demo posts')
    return True
